"""Regression checks for visible column labels in scrolling engineering tables."""

from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
CSS = ROOT / "gui" / "style.css"
INDEX = ROOT / "gui" / "index.html"


def test_shared_sticky_header_applies_to_table_header_cells():
    css = CSS.read_text(encoding="utf-8")
    match = re.search(
        r"table\s*>\s*thead\s*>\s*tr\s*>\s*th\s*\{([^}]*)\}",
        css,
    )
    assert match, "Shared TH sticky rule is missing."
    declaration = match.group(1)
    assert re.search(r"\bposition\s*:\s*sticky\s*;", declaration)
    assert re.search(r"\btop\s*:\s*0\s*;", declaration)
    assert re.search(r"\bz-index\s*:\s*[1-9]\d*\s*;", declaration)
    assert "background:" in declaration
    assert "background-clip: padding-box;" in declaration
    assert not re.search(
        r"\.hmi-text-table\s+thead\s*\{[^}]*position\s*:\s*sticky",
        css,
    ), "Do not duplicate THEAD and TH sticky positioning."


def test_every_vertically_scrollable_engineering_table_uses_shared_header_rule():
    css = CSS.read_text(encoding="utf-8")
    html = INDEX.read_text(encoding="utf-8")
    expected = (
        "tia-inventory-table-wrapper",       # PLC tags, DB/UDT/program lists
        "tia-structure-member-table-wrapper", # DB and UDT structure members
        "hardware-table-wrapper",            # hardware and addressable channels
        "raw-hardware-table-wrapper",        # diagnostic hardware tree
        "device-generated-table-wrapper",    # device configuration and PLC tags
        "hmi-text-table-wrapper",             # HMI translation/review/preview
    )
    for wrapper in expected:
        assert wrapper in html, f"Missing table wrapper: {wrapper}"
        definition = re.search(
            rf"\.{re.escape(wrapper)}\s*\{{([^}}]*)\}}",
            css,
        )
        assert definition, f"Missing style for {wrapper}"
        assert re.search(
            r"overflow\s*:\s*auto\s*;", definition.group(1)
        ), f"{wrapper} must be a vertical scrolling container."

    # Tables generated by JavaScript keep THEAD/TR/TH markup and benefit
    # from the same global rule without special per-table JS handling.
    assert '<th>PROFINET / device name</th>' in html
    assert '<th>Channel</th>' in html
